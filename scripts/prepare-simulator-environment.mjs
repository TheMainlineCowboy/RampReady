import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const generatedPath = path.join(root, "src/components/RampReadyStandupTrainerTerminal4.jsx");
let generated = fs.readFileSync(generatedPath, "utf8");

const generatedBanner = "// GENERATED by scripts/prepare-terminal4-runtime.mjs";
const importAnchor = 'import { installAuthoredKphxPhotoGround } from "../environment/authoredKphxPhotoGround.js";';
const staticImport = 'import { installStaticGateAircraft } from "../environment/staticGateAircraft.js";';
const objectImport = 'import { installSourceAuthoredAirportObjects } from "../environment/sourceAuthoredAirportObjects.js";';
const equipmentImport = 'import { installStaticRampEquipment } from "../environment/staticRampEquipment.js";';
const datasetAnchor = '    renderer.domElement.dataset.terminal4Placement = "loading";';
const promiseAnchor = "    void Promise.all([terminalLoad, groundLoad, photoGroundLoad])";
const rendererAnchor = "    renderer.shadowMap.enabled = true;";
const sunAnchor = "    sun.castShadow = true;";

if (!generated.startsWith(generatedBanner)) throw new Error("Simulator environment patch requires the prepared Terminal 4 trainer");
for (const [anchor, label] of [[importAnchor, "import"], [datasetAnchor, "dataset"], [promiseAnchor, "readiness"], [rendererAnchor, "renderer"], [sunAnchor, "sun"]]) {
  if (!generated.includes(anchor)) throw new Error(`Simulator environment ${label} anchor is missing`);
}

generated = generated.replace(importAnchor, `${importAnchor}\n${staticImport}\n${objectImport}\n${equipmentImport}`);
generated = generated.replace(
  rendererAnchor,
  `${rendererAnchor}\n    renderer.shadowMap.type = THREE.PCFSoftShadowMap;\n    renderer.outputColorSpace = THREE.SRGBColorSpace;\n    renderer.toneMapping = THREE.ACESFilmicToneMapping;\n    renderer.toneMappingExposure = 1.08;`,
);
generated = generated.replace(
  sunAnchor,
  `${sunAnchor}\n    sun.shadow.mapSize.set(2048, 2048);\n    sun.shadow.camera.left = -190;\n    sun.shadow.camera.right = 190;\n    sun.shadow.camera.top = 190;\n    sun.shadow.camera.bottom = -190;\n    sun.shadow.camera.near = 1;\n    sun.shadow.camera.far = 520;\n    sun.shadow.bias = -0.00035;\n    sun.shadow.normalBias = 0.025;`,
);
generated = generated.replace(
  datasetAnchor,
  `${datasetAnchor}\n    renderer.domElement.dataset.visualQuality = "simulator-rendering-v1";\n    renderer.domElement.dataset.staticAircraftCount = "loading";\n    renderer.domElement.dataset.staticAircraftGates = "loading";\n    renderer.domElement.dataset.staticAircraftDetailLevel = "loading";\n    renderer.domElement.dataset.sourceObjectPlacementCount = "loading";\n    renderer.domElement.dataset.sourceObjectModelCount = "loading";\n    renderer.domElement.dataset.sourceObjectTextureCount = "loading";\n    renderer.domElement.dataset.sourceObjectTexturedMaterialCount = "loading";\n    renderer.domElement.dataset.sourceObjectDetailLevel = "loading";\n    renderer.domElement.dataset.staticRampAuthoredTugCount = "loading";\n    renderer.domElement.dataset.staticRampSafetyConeCount = "loading";\n    renderer.domElement.dataset.staticRampEquipmentObjectCount = "loading";\n    renderer.domElement.dataset.staticRampEquipmentDetailLevel = "loading";`,
);

const populatedLoads = `    const staticAircraftLoad = installStaticGateAircraft(THREE, environment)
      .then((staticAircraft) => {
        renderer.domElement.dataset.staticAircraftCount = String(environment.userData.authoredStaticAircraftCount);
        renderer.domElement.dataset.staticAircraftGates = environment.userData.authoredStaticAircraftGates.join(",");
        renderer.domElement.dataset.staticAircraftDetailLevel = environment.userData.authoredStaticAircraftDetailLevel;
        return staticAircraft;
      })
      .catch((error) => {
        renderer.domElement.dataset.staticAircraftCount = "load-error";
        renderer.domElement.dataset.staticAircraftGates = "load-error";
        renderer.domElement.dataset.staticAircraftDetailLevel = "load-error";
        console.error("RampReady PHX static aircraft load failed", error);
        setMessage(\`PHX static aircraft failed to load: \${error.message}\`);
        throw error;
      });
    const sourceObjectLoad = installSourceAuthoredAirportObjects(THREE, environment)
      .then((objects) => {
        renderer.domElement.dataset.sourceObjectPlacementCount = String(environment.userData.sourceAuthoredAirportObjectPlacementCount);
        renderer.domElement.dataset.sourceObjectModelCount = String(environment.userData.sourceAuthoredAirportObjectModelCount);
        renderer.domElement.dataset.sourceObjectTextureCount = String(environment.userData.sourceAuthoredAirportObjectTextureCount);
        renderer.domElement.dataset.sourceObjectTexturedMaterialCount = String(environment.userData.sourceAuthoredAirportObjectTexturedMaterialCount);
        renderer.domElement.dataset.sourceObjectDetailLevel = environment.userData.sourceAuthoredAirportObjectDetailLevel;
        return objects;
      })
      .catch((error) => {
        renderer.domElement.dataset.sourceObjectPlacementCount = "load-error";
        renderer.domElement.dataset.sourceObjectModelCount = "load-error";
        renderer.domElement.dataset.sourceObjectTextureCount = "load-error";
        renderer.domElement.dataset.sourceObjectTexturedMaterialCount = "load-error";
        renderer.domElement.dataset.sourceObjectDetailLevel = "load-error";
        console.error("RampReady PHX source object load failed", error);
        setMessage(\`PHX source objects failed to load: \${error.message}\`);
        throw error;
      });
    const rampEquipmentLoad = installStaticRampEquipment(THREE, environment)
      .then((equipment) => {
        renderer.domElement.dataset.staticRampAuthoredTugCount = String(environment.userData.staticRampAuthoredTugCount);
        renderer.domElement.dataset.staticRampSafetyConeCount = String(environment.userData.staticRampSafetyConeCount);
        renderer.domElement.dataset.staticRampEquipmentObjectCount = String(environment.userData.staticRampEquipmentObjectCount);
        renderer.domElement.dataset.staticRampEquipmentDetailLevel = environment.userData.staticRampEquipmentDetailLevel;
        return equipment;
      })
      .catch((error) => {
        renderer.domElement.dataset.staticRampAuthoredTugCount = "load-error";
        renderer.domElement.dataset.staticRampSafetyConeCount = "load-error";
        renderer.domElement.dataset.staticRampEquipmentObjectCount = "load-error";
        renderer.domElement.dataset.staticRampEquipmentDetailLevel = "load-error";
        console.error("RampReady PHX static ramp equipment load failed", error);
        setMessage(\`PHX ramp equipment failed to load: \${error.message}\`);
        throw error;
      });
    void Promise.all([terminalLoad, groundLoad, photoGroundLoad, staticAircraftLoad, sourceObjectLoad, rampEquipmentLoad])`;

generated = generated.replace(promiseAnchor, populatedLoads);

for (const required of [
  staticImport,
  objectImport,
  equipmentImport,
  'dataset.visualQuality = "simulator-rendering-v1"',
  'renderer.toneMapping = THREE.ACESFilmicToneMapping',
  'renderer.shadowMap.type = THREE.PCFSoftShadowMap',
  'sun.shadow.mapSize.set(2048, 2048)',
  'dataset.staticAircraftCount = "loading"',
  'dataset.sourceObjectPlacementCount = "loading"',
  'dataset.sourceObjectTextureCount = "loading"',
  'dataset.staticRampAuthoredTugCount = "loading"',
  "installStaticGateAircraft(THREE, environment)",
  "installSourceAuthoredAirportObjects(THREE, environment)",
  "installStaticRampEquipment(THREE, environment)",
  "environment.userData.authoredStaticAircraftCount",
  "environment.userData.sourceAuthoredAirportObjectPlacementCount",
  "environment.userData.sourceAuthoredAirportObjectTextureCount",
  "environment.userData.staticRampAuthoredTugCount",
  "Promise.all([terminalLoad, groundLoad, photoGroundLoad, staticAircraftLoad, sourceObjectLoad, rampEquipmentLoad])",
]) {
  if (!generated.includes(required)) throw new Error(`Simulator environment preparation missing ${required}`);
}

fs.writeFileSync(generatedPath, generated);
console.log("RampReady simulator environment prepared with soft airport-wide shadows, ACES rendering, A2-A8 aircraft, textured source objects and authored ramp equipment.");
