import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const generatedPath = path.join(root, "src/components/RampReadyStandupTrainerTerminal4.jsx");
let generated = fs.readFileSync(generatedPath, "utf8");

const generatedBanner = "// GENERATED by scripts/prepare-terminal4-runtime.mjs";
const importAnchor = 'import { installAuthoredKphxPhotoGround } from "../environment/authoredKphxPhotoGround.js";';
const staticImport = 'import { installStaticGateAircraft } from "../environment/staticGateAircraft.js";';
const datasetAnchor = '    renderer.domElement.dataset.terminal4Placement = "loading";';
const promiseAnchor = "    void Promise.all([terminalLoad, groundLoad, photoGroundLoad])";

if (!generated.startsWith(generatedBanner)) {
  throw new Error("Simulator environment patch requires the prepared Terminal 4 trainer");
}
if (!generated.includes(importAnchor)) throw new Error("Simulator environment import anchor is missing");
if (!generated.includes(datasetAnchor)) throw new Error("Simulator environment dataset anchor is missing");
if (!generated.includes(promiseAnchor)) throw new Error("Simulator environment readiness anchor is missing");

if (!generated.includes(staticImport)) {
  generated = generated.replace(importAnchor, `${importAnchor}\n${staticImport}`);
}

if (!generated.includes('dataset.staticAircraftCount = "loading"')) {
  generated = generated.replace(
    datasetAnchor,
    `${datasetAnchor}\n    renderer.domElement.dataset.staticAircraftCount = "loading";\n    renderer.domElement.dataset.staticAircraftGates = "loading";\n    renderer.domElement.dataset.staticAircraftDetailLevel = "loading";`,
  );
}

const staticLoad = `    const staticAircraftLoad = installStaticGateAircraft(THREE, environment)
      .then((staticAircraft) => {
        renderer.domElement.dataset.staticAircraftCount = String(environment.userData.authoredStaticAircraftCount);
        renderer.domElement.dataset.staticAircraftGates = environment.userData.authoredStaticAircraftGates.join(",");
        renderer.domElement.dataset.staticAircraftDetailLevel = environment.userData.authoredStaticAircraftDetailLevel;
        return staticAircraft;
      })
      .catch((error) => {
        renderer.domElement.dataset.staticAircraftCount = "load-error";
        renderer.domElement.dataset.staticAircraftGates = "load-error";
        renderer.domElement.dataset.staticAircraftDetailLevel = "load-error";
        console.error("RampReady PHX static aircraft load failed", error);
        setMessage(\`PHX static aircraft failed to load: \${error.message}\`);
        throw error;
      });
    void Promise.all([terminalLoad, groundLoad, photoGroundLoad, staticAircraftLoad])`;

if (!generated.includes("const staticAircraftLoad = installStaticGateAircraft")) {
  generated = generated.replace(promiseAnchor, staticLoad);
}

for (const required of [
  staticImport,
  'dataset.staticAircraftCount = "loading"',
  "installStaticGateAircraft(THREE, environment)",
  "environment.userData.authoredStaticAircraftCount",
  "Promise.all([terminalLoad, groundLoad, photoGroundLoad, staticAircraftLoad])",
]) {
  if (!generated.includes(required)) throw new Error(`Simulator environment preparation missing ${required}`);
}

fs.writeFileSync(generatedPath, generated);
console.log("RampReady simulator environment prepared with source-aligned static aircraft at A2-A8.");
